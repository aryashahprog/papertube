const titleKey = (title: string) => title.normalize("NFKC").toLowerCase()
  .replace(/[^\p{L}\p{N}]+/gu, " ").trim();

export const paperFigure = (paper: Pick<Paper, "title">) => figures[titleKey(paper.title)];

type SketchKind = "retrieval" | "diffusion" | "dit" | "attention" | "editing" | "particles" | "quantum" | "trial" | "review" | "receptor" | "aging" | "electrical" | "study";
export interface PaperSketch {
  kind: SketchKind;
  labels: string[];
  description: string;
}

// Topic sketches explain a mechanism, not the individual paper's reported results.
// Match the title, not the search query: unrelated hits keep their own visual.
export function paperSketch(paper: Pick<Paper, "title">): PaperSketch {
  const title = paper.title.toLowerCase();
  if (titleKey(title) === "scalable diffusion models with transformers") return {
    kind: "dit", labels: ["Noisy patches", "Transformer", "Predict noise"],
    description: "DiT: split a noisy latent image into patches, process them with a Transformer, and predict noise to remove.",
  };
  if (/retrieval[ -]augmented/.test(title)) return {
    kind: "retrieval", labels: ["Question", "Find sources", "Answer"],
    description: "Retrieval-augmented generation: find relevant sources, then use them to help answer a question.",
  };
  if (/diffusion/.test(title) && /image|generat|denois|text.to.image|latent|synthesis/.test(title)) return {
    kind: "diffusion", labels: ["Noise", "Denoise", "Image"],
    description: "Image diffusion: a learned model removes noise step by step to form an image.",
  };
  // "Transformer" also names electrical hardware. Require positive ML context
  // instead of trying to enumerate every electrical use of the word.
  if (/\bbert\b|self.attention|multi.head attention/.test(title) ||
      titleKey(title) === "attention is all you need" ||
      (/\btransformers?\b/.test(title) && /\b(neural|learning|language|vision|image|images|text|nlp|attention|pretraining|pre training|segmentation|detection|recognition)\b/.test(title))) return {
    kind: "attention", labels: ["Input pieces", "Share context", "Representation"],
    description: "Attention: relate pieces of an input to one another to build context.",
  };
  if (/crispr|cas9|genome editing|gene editing|rna.guided.*dna endonuclease/.test(title)) return {
    kind: "editing", labels: ["Guide RNA", "Matching target", "Action"],
    description: "CRISPR systems: a guide RNA directs the system to a matching target sequence. The action depends on the system.",
  };
  if (/microplastics?|nanoplastics?|plastic (particle|debris|pollution)|plastics ever made/.test(title)) return {
    kind: "particles", labels: ["Plastic", "Tiny particles", "Exposure"],
    description: "Microplastics: small plastic particles can move through the environment and create routes of exposure.",
  };
  if (/quantum error correction|quantum error.correcting|surface code/.test(title)) return {
    kind: "quantum", labels: ["Encode", "Check errors", "Recover"],
    description: "Quantum error correction: encode information across physical qubits, check for errors, and recover logical information.",
  };
  // Reviews can mention randomized trials without assigning participants themselves.
  if (/systematic review|meta.analysis|\bsurvey\b|\breview\b/.test(title)) return {
    kind: "review", labels: ["Studies", "Bring together", "Evidence"],
    description: "Evidence review: bring multiple studies together to examine what is known. This is a study-design sketch, not a result.",
  };
  if (/randomi[sz]ed|placebo.controlled/.test(title) && /trial|patients|adults|children|clinical/.test(title)) return {
    kind: "trial", labels: ["Participants", "Study groups", "Compare outcomes"],
    description: "Trial design: assign participants to treatment and comparison groups, then compare outcomes. No treatment effect is implied.",
  };
  if (/semaglutide|liraglutide|tirzepatide/.test(title) ||
      (/glp.?1|glucagon.like peptide.?1/.test(title) && /receptor|agonist/.test(title))) return {
    kind: "receptor", labels: ["Drug", "Receptor", "Cell signal"],
    description: "GLP-1 medicines: a drug binds a receptor and triggers a signal inside the cell. This illustrates the mechanism, not a clinical outcome.",
  };
  if (/autophagy|senescence|hallmarks of ag[ei]ing|hallmarks of aging/.test(title) ||
      (/aging|ageing|longevity/.test(title) && /cell|metabol|genetic|epigen|spermidine|calorie|stress resistance|genome|protein|mechanism/.test(title))) return {
    kind: "aging", labels: ["Cell damage", "Cell repair", "Cell health"],
    description: "Aging biology: damage and repair both shape cell health. The sketch does not imply that this paper reverses aging.",
  };
  if (/transformers?/.test(title) && /power|electrical|voltage|insulation|liquid.filled|silicon rf/.test(title)) return {
    kind: "electrical", labels: ["Input coil", "Magnetic field", "Output coil"],
    description: "Electrical transformers transfer energy between coils through a changing magnetic field, rather than neural attention.",
  };
  // An unfamiliar subject gets a quiet research glyph, never a made-up mechanism
  // or three arbitrary chunks of its title. Specific sketches above explain only
  // mechanisms or study designs that can be identified confidently from a title.
  return {
    kind: "study", labels: ["Research"],
    description: "Research paper. Open the paper for its method and findings; no mechanism is inferred from this title.",
  };
}
